import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {chromium} from 'playwright';
const root=process.cwd();
const demo=path.resolve(root,'../doctorchart-video-tutorial/.local');
const cert=new crypto.X509Certificate(fs.readFileSync(path.join(demo,'certs/server.pem')));
const pin=crypto.createHash('sha256').update(cert.publicKey.export({type:'spki',format:'der'})).digest('base64');
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--ignore-certificate-errors-spki-list='+pin]});
const context=await browser.newContext({viewport:{width:1000,height:1250},deviceScaleFactor:2,locale:'es-AR',timezoneId:'America/Argentina/Buenos_Aires',colorScheme:'light'});
await context.route('**/*',route=>['localhost','127.0.0.1'].includes(new URL(route.request().url()).hostname)?route.continue():route.abort());
const page=await context.newPage();
const account=JSON.parse(fs.readFileSync(path.join(demo,'accounts.json'),'utf8')).B;
const errors=[];page.on('pageerror',e=>errors.push(e.message.slice(0,150)));
const records=[];
async function shot(id){await page.evaluate(()=>document.fonts.ready);await page.waitForTimeout(500);await page.screenshot({path:path.join(root,'public/assets',id+'.png')});records.push({id,url:page.url().replace(/\d+/g,'[demo-id]'),viewport:{width:1000,height:1250},deviceScaleFactor:2,method:'Playwright screenshot of real frontend, real local demo API, no mocked responses',sha256:crypto.createHash('sha256').update(fs.readFileSync(path.join(root,'public/assets',id+'.png'))).digest('hex')});console.log('Captured '+id);}
try{
 await page.goto('http://localhost:24202/login');
 await page.getByLabel('Correo electrónico',{exact:true}).fill(account.email);
 await page.getByLabel('Contraseña',{exact:true}).fill(account.password);
 await page.getByRole('button',{name:'Ingresar a DoctorChart',exact:true}).click();
 await page.waitForURL('**/dashboard',{timeout:45000});
 await page.getByRole('link',{name:'Ver directorio',exact:true}).waitFor();
 await page.goto('http://localhost:24202/patients');
 await page.getByRole('button',{name:'Ver Ficha'}).first().waitFor({timeout:20000}).catch(()=>{});
 await page.getByText('Persona DEMO 01 Tutorial Ficticio',{exact:true}).first().waitFor({state:'attached'});
 await shot('patients');
 await page.locator('button:visible').filter({hasText:/Ver Ficha/}).first().click();
 await page.getByText('Datos Filiatorios y Clínicos',{exact:true}).waitFor();
 await shot('record');
 await page.locator('button:visible').filter({hasText:/Historia Clínica/}).first().click();
 await shot('history');
 const recordUrl=page.url();
 await page.getByRole('button',{name:'Ver detalle',exact:false}).last().click();
 await page.getByRole('heading',{name:'Detalle de la consulta',exact:true}).waitFor();
 await shot('detail');
 await page.goto(recordUrl);
 await page.getByText('Datos Filiatorios y Clínicos',{exact:true}).waitFor();
 await page.getByRole('button',{name:/Nueva historia clínica/i}).first().click();
 await page.getByText('Nueva Historia Clínica',{exact:true}).waitFor();
 await page.getByLabel('Motivo de consulta',{exact:false}).last().fill('DEMO · Control de seguimiento.').catch(()=>{});
 await shot('encounter');
 await page.goto('http://localhost:24202/onboarding/setup');
 await page.getByRole('heading').first().waitFor();
 await shot('customize');
 await page.locator('.step-button').last().click();
 await page.getByRole('heading',{name:'Historia Clínica',exact:true}).scrollIntoViewIfNeeded();
 await shot('custom-fields');
 console.log(JSON.stringify({status:'CAPTURED',count:records.length,errors}));
}finally{await page.screenshot({path:'qa/capture-last-state.png'});fs.writeFileSync('qa/capture-last-state.txt',await page.locator('body').innerText());fs.writeFileSync('assets/capture-manifest.json',JSON.stringify({date:new Date().toISOString(),records,errors},null,2));await browser.close();}
